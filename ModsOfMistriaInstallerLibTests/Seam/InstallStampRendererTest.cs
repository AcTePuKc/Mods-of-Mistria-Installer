using Garethp.ModsOfMistriaInstallerLib.Seam;

namespace ModsOfMistriaInstallerLibTests.Seam;

[TestFixture]
public class InstallStampRendererTest
{
    [Test]
    public void ShouldRenderAParseableEscapedAimVersion()
    {
        var stamp = InstallStampRenderer.Render("0.2.3-rc.1\\\"test");

        Assert.That(stamp, Does.Contain("global.__aim_installer_version = \"0.2.3-rc.1\\\\\\\"test\";"));
        Assert.That(stamp, Does.Contain("GENERATED BY AIM"));
    }
}
